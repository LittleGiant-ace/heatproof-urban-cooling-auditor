// Deterministic SYNTHETIC data generator (seeded). Nothing here is real observation data.
const fs = require('fs'), path = require('path');
const rng = s => () => { s |= 0; s = s + 0x6D2B79F5 | 0; let t = Math.imul(s ^ s >>> 15, 1 | s); t = t + Math.imul(t ^ t >>> 7, 61 | t) ^ t; return ((t ^ t >>> 14) >>> 0) / 4294967296; };
const dates = []; for (let d = Date.UTC(2025, 2, 1); d <= Date.UTC(2025, 5, 28); d += 7 * 864e5) dates.push(new Date(d).toISOString().slice(0, 10));
const INTERVENTION = '2025-05-01';
function make(seed, { effect, trendT, outlier, drop }) {
  const R = rng(seed), rows = ['site,date,group,surface_temp_c,unit'];
  const sites = [['Park-Ward-A', 'treatment', 0], ['Park-Ward-B', 'treatment', 0.4], ['Park-Ward-C', 'treatment', -0.3], ['Ctrl-North', 'control', 0.2], ['Ctrl-East', 'control', -0.1], ['Ctrl-South', 'control', 0.5]];
  dates.forEach((d, i) => { const season = 0.12 * i + 1.5 * Math.sin(i / 2.2); // shared weather/season signal
    sites.forEach(([s, g, off]) => { if (drop && s === 'Ctrl-East' && (i === 5 || i === 11)) return;
      let v = 36 + off + season + (R() - .5) * 0.8;
      if (g === 'treatment') { v += trendT * i; if (d >= INTERVENTION) v += effect; }
      if (outlier && s === 'Park-Ward-B' && i === 14) v += 7.5;
      rows.push(`${s},${d},${g},${v.toFixed(2)},C`); }); });
  return rows.join('\n') + '\n';
}
const sets = {
  'demo_synthetic.csv': make(11, { effect: -1.2, trendT: 0, outlier: true, drop: true }),
  'misleading_synthetic.csv': make(23, { effect: 0, trendT: -0.09, outlier: false, drop: false })
};
let js = 'window.HP_SAMPLES = {\n';
for (const [n, c] of Object.entries(sets)) { fs.writeFileSync(path.join(__dirname, '..', 'data', n), c); js += `${JSON.stringify(n)}: ${JSON.stringify(c)},\n`; }
fs.writeFileSync(path.join(__dirname, '..', 'samples.js'), '// GENERATED by scripts/generate-data.js — SYNTHETIC data only\n' + js + '};\n');
console.log('generated', Object.keys(sets).join(', '));
